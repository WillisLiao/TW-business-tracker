// Writes wrangler.toml for the Cloudflare Pages project from site.config.json.
// Usage: node scripts/write-wrangler-config.mjs [d1-database-id] [kv-namespace-id]
// The ids are looked up by the GitHub Action (scripts/cf-ids.mjs); locally any placeholder works.

import fs from 'node:fs';

const cfg = JSON.parse(fs.readFileSync('site.config.json', 'utf8'));
const d1Id = process.argv[2] || '00000000-0000-0000-0000-000000000000';
const kvId = process.argv[3] || '00000000000000000000000000000000';
const q = (s) => JSON.stringify(String(s));

fs.writeFileSync('wrangler.toml', `# Generated by scripts/write-wrangler-config.mjs - edit site.config.json instead.
name = "taiwan-monthly"
pages_build_output_dir = "dist"
compatibility_date = "2026-09-01"

[vars]
SITE_URL = ${q(cfg.siteUrl)}
SITE_NAME = ${q(cfg.siteName)}
MAX_WATCHLIST = ${q(cfg.pro.maxWatchlist)}

[[d1_databases]]
binding = "DB"
database_name = "taiwan-monthly"
database_id = ${q(d1Id)}

[[kv_namespaces]]
binding = "EXPORTS"
id = ${q(kvId)}
`);
console.log('wrote wrangler.toml');
